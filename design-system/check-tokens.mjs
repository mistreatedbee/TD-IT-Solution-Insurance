// Fails if a CSS custom property in tokens.css has no entry in tokens.json, or vice versa.
// Also fails if src/styles/td-tokens.css is stale relative to tokens.css.
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const json = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const css = readFileSync(join(here, 'tokens.css'), 'utf8');

const fromJson = new Set([
  ...json.color.tokens.map((t) => t.name),
  ...json.spacing.tokens.map((t) => t.name),
  ...json.radius.tokens.map((t) => t.name),
  ...json.shadow.tokens.map((t) => t.name),
  ...json.blur.tokens.map((t) => t.name),
  ...Object.keys(json.type.families).map((f) => `font-${f}`),
]);
const fromCss = new Set([...css.matchAll(/^\s*--([a-z0-9-]+)\s*:/gm)].map((m) => m[1]));

const missingInJson = [...fromCss].filter((n) => !fromJson.has(n));
const missingInCss = [...fromJson].filter((n) => !fromCss.has(n));
let failed = false;
if (missingInJson.length) { failed = true; console.error('In tokens.css but not tokens.json:', missingInJson.join(', ')); }
if (missingInCss.length) { failed = true; console.error('In tokens.json but not tokens.css:', missingInCss.join(', ')); }

const gen = join(here, '..', 'src', 'styles', 'td-tokens.css');
if (!existsSync(gen)) { failed = true; console.error('Missing src/styles/td-tokens.css; run node design-system/build-web-css.mjs'); }
else {
  const expected = '/* GENERATED by design-system/build-web-css.mjs from design-system/tokens.css. Do not edit. */\n' +
    css.replace(/--([a-z0-9-]+)/g, '--td-$1').replace(/url\("fonts\//g, 'url("/fonts/');
  if (readFileSync(gen, 'utf8') !== expected) { failed = true; console.error('src/styles/td-tokens.css is stale; run node design-system/build-web-css.mjs'); }
}
if (failed) process.exit(1);
console.log(`tokens OK (${fromCss.size} CSS vars match tokens.json)`);
