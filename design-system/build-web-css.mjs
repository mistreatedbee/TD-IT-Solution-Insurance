// Generates src/styles/td-tokens.css from design-system/tokens.css.
// The web app already defines --success, --glass-border, --blur-glass, --radius-sm ...
// so every design-system custom property is namespaced --td-* here, and font urls
// are rewritten to /fonts/ (public/fonts). tokens.css itself is never edited.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, 'tokens.css'), 'utf8');
const out = src
  .replace(/--([a-z0-9-]+)/g, '--td-$1')
  .replace(/url\("fonts\//g, 'url("/fonts/');
writeFileSync(
  join(here, '..', 'src', 'styles', 'td-tokens.css'),
  '/* GENERATED by design-system/build-web-css.mjs from design-system/tokens.css. Do not edit. */\n' + out,
);
console.log('wrote src/styles/td-tokens.css');
