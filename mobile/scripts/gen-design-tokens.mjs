#!/usr/bin/env node
/**
 * Generates src/theme/designTokens.generated.ts from the design-system
 * single source of truth (<repo>/design-system/tokens.json).
 *
 *   node scripts/gen-design-tokens.mjs          write the file
 *   node scripts/gen-design-tokens.mjs --check  exit 1 if checked-in file is stale
 *
 * Override the source with DESIGN_TOKENS_PATH. No dependencies.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/theme/designTokens.generated.ts');
const SRC = process.env.DESIGN_TOKENS_PATH
  ? resolve(process.env.DESIGN_TOKENS_PATH)
  : resolve(here, '../../design-system/tokens.json');

if (!existsSync(SRC)) {
  console.error(`tokens.json not found at ${SRC} (set DESIGN_TOKENS_PATH to override)`);
  process.exit(2);
}
const tokens = JSON.parse(readFileSync(SRC, 'utf8'));
const THEMES = ['day', 'night'];

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => Number.parseFloat(String(v));

function hexToRgba(v) {
  const m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(v);
  if (!m) return v;
  const n = Number.parseInt(m[1], 16);
  const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  if (!m[2]) return v.toUpperCase();
  const a = Math.round((Number.parseInt(m[2], 16) / 255) * 1000) / 1000;
  return `rgba(${r}, ${g}, ${b}, ${a})`;
}

// ---- colours (resolve {aliases} per theme)
const raw = new Map(tokens.color.tokens.map((t) => [t.name, t.value]));
function resolveColor(name, theme, seen = []) {
  if (seen.includes(name)) throw new Error(`alias cycle: ${[...seen, name].join(' -> ')}`);
  let v = raw.get(name);
  if (v === undefined) throw new Error(`unknown colour token ${name}`);
  if (typeof v === 'object') v = v[theme];
  const alias = /^\{(.+)\}$/.exec(v);
  return alias ? resolveColor(alias[1], theme, [...seen, name]) : hexToRgba(v);
}
const colors = Object.fromEntries(
  THEMES.map((th) => [th, Object.fromEntries([...raw.keys()].map((n) => [camel(n), resolveColor(n, th)]))]),
);

const spacing = Object.fromEntries(tokens.spacing.tokens.map((t) => [camel(t.name.replace('space-', 's')), px(t.value)]));
const radius = Object.fromEntries(tokens.radius.tokens.map((t) => [camel(t.name.replace('radius-', '')), px(t.value)]));
const blur = Object.fromEntries(tokens.blur.tokens.map((t) => [camel(t.name.replace('blur-', '')), px(t.value)]));

// ---- shadows: "0 8px 32px 0 rgba(44,62,82,0.14)" -> RN props + elevation approximation
function parseShadow(css) {
  const m = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(css.trim());
  if (!m) throw new Error(`unparseable shadow: ${css}`);
  const [x, y, b, , r, g, bl, a] = m.slice(1).map(Number);
  const hex = '#' + [r, g, bl].map((c) => c.toString(16).padStart(2, '0')).join('').toUpperCase();
  return {
    shadowColor: hex,
    shadowOffset: { width: x, height: y },
    shadowOpacity: a,
    shadowRadius: b / 2, // CSS blur radius ~= 2x the iOS shadowRadius
    elevation: Math.min(24, Math.round(b / 4)), // Android has no blur control; approximation
  };
}
const shadows = Object.fromEntries(
  THEMES.map((th) => [th, Object.fromEntries(tokens.shadow.tokens.map((t) => [camel(t.name.replace('shadow-', '')), parseShadow(t.value[th])]))]),
);

// ---- type
const fontNames = {
  display: { 400: 'ZillaSlab-400', 500: 'ZillaSlab-500', 600: 'ZillaSlab-600', 700: 'ZillaSlab-700' },
  sans: { 400: 'PlusJakartaSans-Regular', 500: 'PlusJakartaSans-Medium', 600: 'PlusJakartaSans-SemiBold', 700: 'PlusJakartaSans-Bold' },
};
const typeStyles = {};
for (const g of tokens.type.groups) {
  for (const s of g.styles) {
    const fontSize = px(s.fontSize);
    const fam = fontNames[g.family][s.fontWeight];
    if (!fam) throw new Error(`no font file for ${g.family} ${s.fontWeight} (${s.name})`);
    typeStyles[camel(s.name)] = {
      fontFamily: fam,
      fontSize,
      lineHeight: px(s.lineHeight),
      fontWeight: s.fontWeight,
      letterSpacing: s.letterSpacing ? Math.round(px(s.letterSpacing) * fontSize * 100) / 100 : 0,
    };
  }
}

const motion = {
  duration: { press: 160, state: 240, entrance: 420 },
  easing: { cubicBezier: [0.2, 0.8, 0.2, 1] },
  entranceRise: 12,
  pressScale: 0.98,
};

const J = (v) => JSON.stringify(v, null, 2);
const out = `/* eslint-disable */
// GENERATED by scripts/gen-design-tokens.mjs from design-system/tokens.json — do not edit.
// Regenerate with \`npm run tokens:gen\`.

export const designColorsDay = ${J(colors.day)} as const;

export const designColorsNight = ${J(colors.night)} as const;

export type DesignColors = { [K in keyof typeof designColorsDay]: string };

export const designSpacing = ${J(spacing)} as const;

export const designRadius = ${J(radius)} as const;

export interface DesignShadow {
  shadowColor: string;
  shadowOffset: { width: number; height: number };
  shadowOpacity: number;
  shadowRadius: number;
  elevation: number;
}

export const designShadows: { day: Record<'glass' | 'float', DesignShadow>; night: Record<'glass' | 'float', DesignShadow> } = ${J(shadows)};

export const designBlur = ${J(blur)} as const;

export const designFontFamilies = ${J(fontNames)} as const;

export interface DesignTextStyle {
  fontFamily: string;
  fontSize: number;
  lineHeight: number;
  fontWeight: number;
  letterSpacing: number;
}

export const designTypeStyles = ${J(typeStyles)} as const satisfies Record<string, DesignTextStyle>;

export const designMotion = ${J(motion)} as const;
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== out) {
    console.error('designTokens.generated.ts is stale — run `npm run tokens:gen`');
    process.exit(1);
  }
  console.log('designTokens.generated.ts is up to date');
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
